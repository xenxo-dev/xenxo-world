const DICTS = { es, en } satisfies Record<string, Record<Key, string>>;
export type Lang = keyof typeof DICTS;
export const LANGS: { id: Lang; label: string }[] = [
  { id: "es", label: "Español" },
  { id: "en", label: "English" },
];

function detect(): Lang {
  const saved = loadPref<string | null>("lang", null);
  if (saved && saved in DICTS) return saved as Lang;
  const nav = (navigator.languages?.[0] ?? navigator.language ?? "es").slice(0, 2).toLowerCase();
  return nav in DICTS ? (nav as Lang) : "en";
}

let lang: Lang = detect();
const listeners = new Set<() => void>();
document.documentElement.lang = lang;

export function getLang(): Lang {
  return lang;
}

export function setLang(l: Lang) {
  lang = l;
  savePref("lang", l);
  document.documentElement.lang = l;
  for (const fn of listeners) fn();
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  let s: string = DICTS[lang][key];
  for (const [k, v] of Object.entries(vars)) {
    s = s.replace(`{${k}}`, typeof v === "number" ? v.toLocaleString(lang === "es" ? "es-ES" : "en-GB") : v);
  }
  return s;
}

/**
 * Mensaje legible para un error del servidor o de la validación de modelos.
 * Los errores llevan un código estable; el texto lo pone el cliente en su idioma.
 */
export function errorText(e: unknown): string {
  const err = e as { code?: string; name?: string; detail?: { forbidden?: string[] } } | null;
  if (err?.name === "TypeError") return t("err.network");
  const key = `err.${err?.code ?? ""}`;
  if (key in DICTS[lang]) {
    return t(key as Key, { list: err?.detail?.forbidden?.join(", ") ?? "" });
  }
  return t("err.unknown");
}

/** Ruta de las páginas legales en el idioma actual. */
export function legalPath(doc: "privacy" | "terms"): string {
  if (lang === "es") return doc === "privacy" ? "/legal/privacidad.html" : "/legal/condiciones.html";
  return doc === "privacy" ? "/legal/privacy.html" : "/legal/terms.html";
}

/** Re-renderiza el componente cuando cambia el idioma. */
export function useLang(): Lang {
  return useSyncExternalStore(
    (fn) => {
      listeners.add(fn);
      return () => listeners.delete(fn);
    },
    () => lang,
  );
}

/** Nombres de lugares que llegan como datos (los distritos, de GET /districts). */
const placeNames = new Map<string, Record<string, string>>();
export function registerPlaceName(chunkId: string, names: Record<string, string>) {
  placeNames.set(chunkId, names);
}

/** Nombre de un lugar del mundo por su chunk ("el nexo", "la plaza", "Arcade"…). */
export function placeName(chunkId: string): string {
  const key = `place.${chunkId}`;
  if (key in DICTS[lang]) return t(key as Key);
  const n = placeNames.get(chunkId);
  return n ? (n[lang] ?? n.en ?? Object.values(n)[0]!) : t("place.other");
}
